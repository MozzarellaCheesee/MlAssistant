import pytest

from app.domain.speech_text import normalize_for_speech as n


@pytest.mark.parametrize("src,out", [
    ("в 15:00", "в пятнадцать ноль-ноль"),
    ("в 9:30", "в девять тридцать"),
    ("в 9:05", "в девять ноль пять"),
    ("29 октября", "двадцать девятое октября"),
    ("1 мая", "первое мая"),
    ("20 июня", "двадцатое июня"),
    ("3 задачи", "три задачи"),
    ("100 дел", "сто дел"),
    ("0 дел", "ноль дел"),
    ("101 дело", "101 дело"),
    ("3,5 часа", "3,5 часа"),
    ("29 октября в 15:00, 2 встречи", "двадцать девятое октября в пятнадцать ноль-ноль, две встречи".replace("две", "два")),
    ("без цифр", "без цифр"),
])
def test_normalize(src, out):
    assert n(src) == out
